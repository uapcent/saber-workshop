def build():
    k, cr = EXPLODED_SCALE, CHART_STROKE
    P = {}
    # EVO (photo-measured, fitted to the published lengths)
    P["emitter.evo"] = cap_top(PHOTO["emi_evo"])
    P["emitter.evo2"] = pin_ends(PHOTO["emi_evo2"])
    P["emitter.nxt"] = pin_ends(PHOTO["emi_nxt"])
    P["body.evo"] = pin_ends(PHOTO["body_evo"])
    P["body.mini"] = pin_ends(norm(PHOTO["body_evo"], L=150))
    P["pommel.evo"] = PHOTO["pom_evo"]
    P["pommel.mini"] = norm(PHOTO["pom_evo"], L=20, x0=0, x1=21.3)
    # Pommel Adaptor and masks (exploded diagram): mask, then the 5.8 mm adaptor rim
    std = scale(EXP["mask_std"], k)
    P["pommel.adaptor"] = std + [[round(std[-1][0] + 0.1, 1), 19], [20, 19]]
    P["pommel.adaptor.extra"] = scale(EXP["mask_extra"], k)
    # Legacy (exploded diagram is exact, size chart has 1.4 mm resolution)
    P["body.sse3"] = rdp(scale(EXP["body_sse3"], k), 0.12)
    P["emitter.sse3"] = norm(EXP["emi_sse3"], x0=29, x1=68.4, L=40)
    P["body.sse1"] = norm(CHART["body_sse1"], L=200, rscale=cr)
    P["body.sse2"] = norm(CHART["body_sse2"], L=146.5, rscale=cr)
    P["emitter.x2"] = norm(CHART["emi_x2"], x0=10.6, x1=66, L=55, rscale=cr)
    P["emitter.sse1"] = norm(CHART["emi_sse1"], L=55, rscale=cr)
    P["emitter.sse2"] = norm(CHART["emi_sse2"], L=55, rscale=cr)
    P["emitter.artiglio"] = norm(CHART["emi_art"], x0=10.6, x1=48.9, L=40, rscale=cr)
    P["pommel.sse1"] = norm(CHART["pom_sse1"], L=38, rscale=cr)
    P["pommel.sse3std"] = P["pommel.adaptor"]
    P["pommel.sse3extra"] = P["pommel.adaptor.extra"]
    P["pommel.sse2"] = norm(CHART["pom_sse2"], L=16, rscale=cr)
    return {key: [[x, r] for x, r in pts] for key, pts in P.items()}


if __name__ == "__main__":
    profiles = build()
    with OUT.open("w", encoding="utf8", newline="\n") as f:
        json.dump(profiles, f, indent=0)
    for key, pts in profiles.items():
        print(f"{key:22} length {pts[-1][0]:6.1f} mm, max radius {max(r for _, r in pts):5.2f} mm")
