"""Builds part outlines for Saber Workshop and writes data/profiles.json.

Each outline is a list of [x mm along the hilt from the pommel side, radius mm] pairs.
The React app imports profiles.json directly, so rerunning this script is all it takes.

Sources:
  exploded - official Polaris SSe-3 exploded diagram (Altezze_InternoNumeri.png, 3934 px, to scale: 110 px = 38 mm)
  chart    - official Polaris modular hilts size chart (Altezze, 725 px, 141 px = 200 mm)
  photo    - silhouettes measured from LamaDiLuce product photos (Dark Matter / aluminum), scaled to the
             published lengths and diameters; perspective-corrected for the angled main-body photo.

Usage: python data/build_profiles.py
"""
