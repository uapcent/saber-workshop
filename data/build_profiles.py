def rdp(pts, eps):
    """Ramer-Douglas-Peucker simplification: drop points closer than eps mm to the line."""
    if len(pts) < 3:
        return pts
    (ax, ar), (bx, br) = pts[0], pts[-1]
    seg = math.hypot(br - ar, bx - ax) or 1
    dmax, imax = 0, 0
    for i in range(1, len(pts) - 1):
        x, r = pts[i]
        d = abs((br - ar) * x - (bx - ax) * r + bx * ar - br * ax) / seg
        if d > dmax:
            dmax, imax = d, i
    if dmax > eps:
        return rdp(pts[: imax + 1], eps)[:-1] + rdp(pts[imax:], eps)
    return [pts[0], pts[-1]]


def norm(pts, L=None, x0=None, x1=None, rscale=1.0):
    """Crop to [x0, x1], shift to start at 0, stretch to length L and scale radii."""
    if x0 is not None:
        pts = [(x, r) for x, r in pts if x0 <= x <= x1]
    start = pts[0][0]
    pts = [(x - start, r) for x, r in pts]
    span = pts[-1][0] or 1
    if L:
        pts = [(x * L / span, r) for x, r in pts]
    return [[round(x, 1), round(r * rscale, 2)] for x, r in pts]


def scale(pts, f):
    return [[round(x * f, 1), r] for x, r in pts]


def cap_top(pts):
    """Emitter mouth: the photo silhouette rounds off the rim seen from above; keep the rim at full flare."""
    top = max(r for _, r in pts)
    out, seen = [], False
    for x, r in pts:
        if r >= top - 0.05:
            seen = True
        out.append([x, round(top - 0.4, 2) if seen and r < top - 0.4 else r])
    return out


def pin_ends(pts, r=18.9):
    """Force both ends to at least the thread radius so neighbouring parts meet flush."""
    pts = [list(p) for p in pts]
    pts[0][1] = max(pts[0][1], r)
    pts[-1][1] = max(pts[-1][1], r)
    return pts


